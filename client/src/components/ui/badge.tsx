import * as React from "react"
import { cva, type VariantProps } from "class-variance-authority"
import { cn } from "@/lib/utils"
const badgeVariants = cva(
  "inline-flex items-center rounded-md border px-2.5 py-0.5 text-xs font-semibold transition-colors",
  {
    variants: {
      variant: {
        default: "border-transparent bg-[var(--accent)] text-[var(--accent-fg)]",
        secondary: "border-transparent bg-[var(--bg-elevated)] text-[var(--text-primary)]",
        destructive: "border-transparent bg-[var(--destructive)] text-white",
        outline: "text-[var(--text-primary)] border-[var(--border-default)]",
      },
    },
    defaultVariants: { variant: "default" },
  }
)
export interface BadgeProps extends React.HTMLAttributes<HTMLDivElement>, VariantProps<typeof badgeVariants> {}
function Badge({ className, variant, ...props }: BadgeProps) {
  return <div className={cn(badgeVariants({ variant }), className)} {...props} />
}
export { Badge, badgeVariants }
